export function project(ra: number, dec: number): { x: number; y: number } {
  const z = ((90 - dec) * Math.PI) / 180;
  const r = K * Math.tan(z / 2);
  const t = ((ra * 15 + ROT) * Math.PI) / 180;
  return { x: 50 + r * Math.cos(t), y: 50 + OFFY + r * Math.sin(t) };
}

