/** Texture key for one craft at one lean. The frames are generated by
 *  `buildHover` in the art script, one set per ship, all the same size — which
 *  is load-bearing: `car.ts` swaps them on a live sprite whose resting Y came
 *  from the frame height, so a taller frame would make the craft hop. */
export function shipFrame(ship: ShipSpec, lean: SteerLevel): string {
  const suffix =
    lean === -2 ? "HardLeft" : lean === -1 ? "Left" : lean === 1 ? "Right" : lean === 2 ? "HardRight" : "";
  return ship.art + suffix;
}

/** Every texture key the three craft between them need, in load order. */
export const SHIP_FRAMES: ReadonlyArray<{ key: string; file: string }> = SHIPS.flatMap((ship) =>
  ([-2, -1, 0, 1, 2] as SteerLevel[]).map((lean) => ({
    key: shipFrame(ship, lean),
    file: `${ship.art}${lean === -2 ? "-hard-left" : lean === -1 ? "-left" : lean === 1 ? "-right" : lean === 2 ? "-hard-right" : ""}.png`,
  })),
);
