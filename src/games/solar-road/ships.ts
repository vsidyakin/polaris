/* SOLAR CIRCUIT — the three craft.
 *
 * A ship is a palette, a silhouette and four numbers. The numbers are the part
 * that matters: they scale the speed model in `car.ts`, so choosing a craft is a
 * choice about how the run will go rather than a choice of colour.
 *
 * WHAT THE FOUR DIALS DO, AND WHY THERE ARE ONLY FOUR
 *
 * Every one of them multiplies something that already existed and was already
 * tuned. That is deliberate: a ship cannot introduce a mechanic, only lean on
 * one. It keeps all three balanced against the same model, it keeps the numbers
 * comparable on the selection card, and it means a change to the speed model
 * applies to all three craft at once instead of needing three sets of edits.
 *
 *   top    scales the nominal speed, and therefore the whole ladder above it
 *   grip   scales how fast grip and surge are EARNED, not their ceilings
 *   steer  scales lateral authority
 *   boost  scales what a full meter is worth
 *
 * The three are deliberately not balanced to be equal. VECTOR is the one to
 * learn on and is second-best at everything; LANCE is faster than either in a
 * straight line and will put you in the regolith on `ANTIPODE`; BULWARK is slow
 * and can hold a line through things the other two cannot. Which is best is a
 * question about the course, which is the whole point of choosing after picking
 * a track — and the reason the selection order is ship first, track second is
 * that it is more interesting to pick a track FOR your craft than to have the
 * obvious craft handed to you by the track.
 */

/** How hard the craft is leaning: level, banking, or banking hard. `car.ts`
 *  escalates from one to the next when a turn is held. */
export type SteerLevel = -2 | -1 | 0 | 1 | 2;

export interface ShipSpec {
  /** Stable key. */
  id: string;
  name: string;
  blurb: string;
  /** Texture key prefix; frames are `<art>`, `<art>Left`, `<art>HardLeft`… */
  art: string;
  /** Accent used for this craft on the menus, matching its hull. */
  color: string;
  top: number;
  grip: number;
  steer: number;
  boost: number;
}

